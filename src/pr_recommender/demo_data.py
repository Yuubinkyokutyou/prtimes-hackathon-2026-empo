"""``init.sql`` の架空シードを使う、通信不要のデモデータ。

会社IDとリリースIDの組を識別子として扱う。リリースID単独は複数社で
重複するため、テストやUIでも必ず :attr:`Release.key` を利用する。
"""

from __future__ import annotations

from datetime import datetime

from .models import Company, Release


def _dt(value: str) -> datetime:
    return datetime.fromisoformat(value)


def _release(
    company: Company,
    release_id: int,
    title: str,
    subtitle: str,
    lead: str,
    detail: str,
    release_type: str,
    created_at: str,
    categories: tuple[str, ...],
    keywords: tuple[str, ...],
    metrics: tuple[int, int, int],
    *,
    clipping_count: int = 0,
    pattern: str,
) -> Release:
    page_view, unique_user, like_count = metrics
    return Release(
        company_id=company.company_id,
        release_id=release_id,
        company_name=company.name,
        industry=company.industry,
        title=title,
        subtitle=subtitle,
        lead=lead,
        body=f"{lead}\n\n{detail}\n\n※開発・評価用の架空情報です。",
        release_type=release_type,
        created_at=_dt(created_at),
        categories=categories,
        keywords=keywords,
        page_view=page_view,
        unique_user=unique_user,
        like_count=like_count,
        clipping_count=clipping_count,
        url=(
            "https://prtimes.example/main/html/rd/p/"
            f"{release_id:09d}.{company.company_id:09d}.html"
        ),
        pattern=pattern,
    )


